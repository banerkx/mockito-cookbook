function Convert-Windows-Path-To-Unix
{
  param
  (
    [Parameter(Mandatory)]
    [string]${Path}
  )

################################################################################
# Normalizing the path separators.                                             #
################################################################################
  ${Path} = ${Path} -replace '\\', '/'

################################################################################
# Converting drive letter to /c/ style.                                        #
################################################################################
  if (${Path} -match '^([a-zA-Z]):')
  {
    ${driveLetter} = ${matches}[1].ToLower()
    ${Path} = "/${driveLetter}/${Path}.Substring(2)"
  }

################################################################################
# Ensuring no double slashes.                                                  #
################################################################################
  ${Path} = ${Path} -replace '//+', '/'

  return ${Path}
}

